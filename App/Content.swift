}

enum AdhkarKind: String, CaseIterable, Identifiable {
    case morning, evening, afterPrayer
    var id: String { rawValue }
    var title: String {
        switch self {
        case .morning: return "الصباح"
        case .evening: return "المساء"
        case .afterPrayer: return "بعد الصلاة"
        }
    }
}

